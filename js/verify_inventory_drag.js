// Inventory model and real native-drag handlers; no browser or graphics context.
const assert = require('node:assert/strict');
const {boot} = require('./verify_ships.js');
const w = boot(), {Colony: c, Weapons, Fuel} = w.model;
const find = type => c.bag.findIndex(stack => stack?.type === type);
let from = find('metal'), to = c.bag.findIndex(stack => !stack);
assert(c.moveInventoryStack(from, to, 3));
assert.equal(c.bag[from].qty, 3);
assert.equal(c.bag[to].qty, 3);
assert(c.moveInventoryStack(from, to));
assert.equal(c.bag[to].qty, 6);
assert.equal(c.bag[from], null);
const ice = find('ice');
assert(c.moveInventoryStack(to, ice));
assert.equal(c.bag[ice].type, 'metal');
assert.equal(c.bag[to].type, 'ice');
assert.equal(c.moveInventoryStack(ice, to, 1), false);
assert.equal(c.moveInventoryStack(-1, 0), false);
assert.equal(c.applyInventoryDrop({kind: 'bag', index: 1}, {kind: 'item', type: 'metal', slot: 99}), false);
const before = c.availableCount('metal');
assert(c.applyInventoryDrop({kind: 'cell', index: 0}, {kind: 'item', type: 'metal', slot: ice}));
assert.equal(c.craftingGrid[0], 'metal');
assert.equal(c.availableCount('metal'), before);
assert.equal(c.applyInventoryDrop({kind: 'cell', index: 99}, {kind: 'item', type: 'metal', slot: ice}), false);
// Merges cap at the target stack limit and leave the remainder in the source.
assert(c.addItem('metal', 64));
const ores = c.bag.map((s, i) => s?.type === 'metal' ? i : -1).filter(i => i >= 0);
const full = ores.find(i => c.bag[i].qty === 64), partial = ores.find(i => c.bag[i].qty < 64);
assert(full >= 0 && partial >= 0);
assert.equal(c.moveInventoryStack(partial, full), false);
assert(c.moveInventoryStack(full, partial));
assert.equal(c.availableCount('metal'), before + 64);
// Actual bag drag/drop listeners carry source indexes and support Shift half stacks.
const buttons = c.bag.map((_, index) => ({dataset: {slot: String(index)}}));
w.ctx.document.querySelector('#slots').querySelectorAll = selector => selector === '[data-slot]' ? buttons : [];
c.openInventory();
const source = find('metal'), destination = c.bag.findIndex(s => !s);
let payload = '';
const transfer = {types: ['application/x-spacecraft-quick'], setData(type, value) {payload = value; this.types = [type];}, getData() {return payload;}};
buttons[source].ondragstart({dataTransfer: transfer, shiftKey: true, preventDefault() {}});
assert.equal(JSON.parse(payload).slot, source);
const quantity = JSON.parse(payload).quantity;
buttons[destination].ondrop({dataTransfer: transfer, preventDefault() {}});
assert.equal(c.bag[destination].qty, quantity);
assert(c.addItem('fotron', 1));
assert(c.addItem('ammo_fotron', 3));
assert(c.equipShipSlot('primary', 'fotron'));
assert.equal(Weapons.selected.primary, 'fotron');
assert(c.equipShipSlot('primaryAmmo', 'ammo_fotron'));
assert.equal(c.equipShipSlot('missile', 'fotron'), false);
assert.equal(c.equipShipSlot('primaryAmmo', 'ammo_bulshitter'), false);
const cubes = c.availableCount('ion_cube');
Fuel.drive(1, false, 10000);
assert(c.equipShipSlot('fuel', 'ion_cube'));
assert.equal(c.availableCount('ion_cube'), cubes - 1);
assert(Fuel.amount > 0);
const markup = w.ctx.document.querySelector('#slots').innerHTML;
assert(markup.includes('ship-blueprint') && markup.includes('data-ship-slot="fuel"'));
assert(markup.includes('inventory-cargo-pane') && markup.includes('inventory-craft-pane'));
c.save();
const reload = boot(w.store).model.Colony;
assert.equal(reload.availableCount('metal'), c.availableCount('metal'));
console.log('PASS: drag move/merge/swap, half stacks, limits, invalid payloads, non-consuming recipe cells, real drag/drop handlers, equipment compatibility, fuel tank use and save reload. No browser started.');
