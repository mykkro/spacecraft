// Real encounter/recruitment/save lifecycle and encyclopedia; no browser.
const assert=require('node:assert/strict'),fs=require('node:fs');
const {boot}=require('./verify_ships.js');
const w=boot(undefined,{withStarbases:true}),c=w.model.Colony,s=w.run('Starbases');
w.ctx.GameAudio.setEngine=()=>{};
assert.equal(s.characters().length,0,'Unconfirmed ship previews do not reveal characters');
w.model.Shipyard.choose('kraxna'); c.save();
assert.deepEqual(Array.from(s.characters(),p=>p.id).sort(),['character:bobo','character:jegor']);
assert(s.characters().find(p=>p.id==='character:bobo').description.includes('50%'));
Object.assign(w.ctx.ship,{x:1800,y:1100,vx:0,vy:0});
assert(s.openDock());
assert.equal(s.characters().length,5);
assert(s.characters().find(p=>p.name==='Rhea').status==='Met');
assert(s.hire('miner'));
assert(s.characters().find(p=>p.name==='Rhea').status==='On board');
s.closeDock();
w.model.Shipyard.choose('nomad'); c.save();
const reload=boot(w.store,{withStarbases:true});
const people=reload.run('Starbases.characters()');
assert.equal(people.find(p=>p.id==='character:bobo').status,'Met');
assert.equal(people.find(p=>p.name==='Rhea').status,'On board');
assert.equal(people.find(p=>p.id==='character:captain').status,'Current captain');
assert.equal(people.length,6);
reload.ctx.GameAudio.setEngine=()=>{};
reload.ctx.document.querySelector('#shipyardOverlay').hidden=true;
reload.ctx.document.querySelector('#overlay').hidden=true;
reload.run(fs.readFileSync('js/encyclopedia.js','utf8'));
const guide=reload.run('Encyclopedia');
assert.equal(guide.entries('','characters').length,6);
assert.equal(guide.entries('Bobo','characters')[0].id,'character:bobo');
assert(guide.showItem('character:miner'));
const html=reload.ctx.document.querySelector('#encyclopediaDetails').innerHTML;
assert(html.includes('rhea.png')&&html.includes('25%')&&html.includes('On board'));
assert(!html.includes('Stack limit'));
assert.equal(guide.getEntry('character:unknown'),null);
const old=JSON.parse(w.store.get('spacecraft-save-v1'));
delete old.starbases.met;
const legacy=boot(new Map([['spacecraft-save-v1',JSON.stringify(old)]]),{withStarbases:true});
assert(legacy.run('Starbases.characters()').some(p=>p.name==='Rhea'),'Old hired crew are migrated');
legacy.run('Starbases.restore({met:["unknown",null,"bobo","bobo"]})');
assert.equal(legacy.run('Starbases.characters()').filter(p=>p.id==='character:bobo').length,1);
assert.equal(boot(undefined,{withStarbases:true}).run('Starbases.characters().length'),0);
console.log('PASS: encounter discovery, starting crew, recruitment, ship switching, save reload, legacy crew, catalogue portraits/search/details and fresh-profile isolation. No browser started.');
