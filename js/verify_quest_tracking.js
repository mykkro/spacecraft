// Real quest/navigation models with a canvas spy; no browser.
const assert=require('node:assert/strict'),fs=require('node:fs');
const {boot}=require('./verify_ships.js');
function world(saved){
  const w=boot(saved,{withStarbases:true,withMissions:true,withTracker:true});
  w.ctx.GameAudio.setEngine=()=>{};w.ctx.drops=[];w.ctx.radar=()=>{};w.ctx.devicePixelRatio=1;
  const calls=[];
  const pen=new Proxy({}, {get(target,key){
    if(key in target)return target[key];
    if(key==='createRadialGradient')return ()=>({addColorStop(){}});
    return (...args)=>calls.push([key,...args]);
  }});
  const canvas=w.ctx.document.querySelector('#chart');
  canvas.getContext=()=>pen;canvas.getBoundingClientRect=()=>({width:800,height:500});
  const objects=w.ctx.document.querySelector('#mapObjects');
  objects.insertAdjacentHTML=function(position,html){this.innerHTML=(this.innerHTML||'')+html;};
  for(const file of ['navigation.js','pirates.js','quests.js'])w.run(fs.readFileSync('js/'+file,'utf8'));
  return {...w,...w.run('({QuestTracker,QuestLog,StarChart,MissionContracts})'),pen,calls};
}
const w=world(),t=w.QuestTracker,c=w.model.Colony;
assert.equal(t.track('invalid'),false);
assert(w.MissionContracts.accept('haul-ingots'));
assert(t.track('haul-ingots'));
assert.equal(t.target().system,'1:0');
let point=t.waypoint();
assert(point.via&&point.to==='1:0');
assert.equal(point.x,w.StarChart.portals().find(p=>p.to==='1:0').x);
t.drawRadar(w.pen);
t.drawLocal(w.pen,(x,y)=>({x,y}));
t.drawGlobal(w.pen,s=>({x:s.gx*100,y:s.gy*100}));
assert(w.calls.some(call=>call[0]==='fillText'&&String(call[1]).includes('Wormhole')));
assert(w.calls.some(call=>call[0]==='fillText'&&call[1]===w.QuestLog.getDefinition('haul-ingots').title));
c.save();
const reload=world(w.store);
assert.equal(reload.QuestTracker.selected,'haul-ingots','Selection survives early startup autosave');
Object.assign(reload.ctx.ship,{x:12000,y:0});
point=reload.QuestTracker.waypoint();
assert.equal(point.via,false);
assert.equal(point.x,reload.run('Starbases.station(1,0).x'));
Object.assign(reload.ctx.ship,{x:24000,y:12000});
point=reload.QuestTracker.waypoint();
assert(point.via);
const [x,y]=point.to.split(':').map(Number);
assert(Math.abs(x-1)+Math.abs(y)<2,'Hop reduces distance to destination');
assert(t.track('escort-courier'));
assert.equal(t.target().system,'0:0');
assert(w.MissionContracts.accept('escort-courier'));
assert.equal(t.target().x,w.MissionContracts.courier.x);
w.ctx.rocks.push({x:100,y:200,type:'crystal'},{x:900,y:900,type:'metal'});
assert(t.track('mine-crystal'));
assert.equal(t.target().x,100);
c.recordMined('crystal',12);
assert.equal(t.target(),null);
assert(t.track('first-base'));assert(t.target(),'Build-base quest has a moon target');
assert(t.track(null));assert.equal(t.waypoint(),null);
t.update(1);assert.equal(t.selected,null);
w.QuestLog.openLog();
assert(w.ctx.document.querySelector('#questCards').innerHTML.includes('data-track-quest'));
console.log('PASS: tracked selection, target resolution, wormhole hops, arrival switch, courier/mining/base targets, marker drawing, UI and save/reload. No browser started.');
