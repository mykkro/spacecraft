// Batch crafting uses real inventory, timers and persisted queue state; no browser.
const assert=require('node:assert/strict');
const {boot}=require('./verify_ships.js');
const w=boot(),c=w.model.Colony;
const choose=out=>assert(c.selectRecipe(c.recipes.findIndex(r=>r.out===out)));
choose('block');
c.addItem('stone',40);
const before=c.availableCount('stone'),blocks=c.availableCount('block'),mass=c.cargoMass;
const max=Math.floor(before/2);
assert.equal(c.maxCraftQuantity(),max);
c.setCraftQuantity(10);
assert(c.craft());
assert.equal(c.craftingQueue.length,1);
assert.equal(c.craftingQueue[0].qty,40);
assert.equal(c.craftingQueue[0].duration,10);
assert.equal(c.availableCount('stone'),before-20);
assert.equal(c.cargoMass,mass);
for(let i=0;i<5;i++)c.updateCrafting(.5);
c.save();
const reload=boot(w.store).model.Colony;
assert.equal(reload.craftingQueue[0].batches,10);
assert.equal(reload.craftingQueue[0].remaining,7.5);
for(let i=0;i<15;i++)reload.updateCrafting(.5);
assert.equal(reload.availableCount('block'),blocks+40);
assert.equal(reload.craftingQueue.length,0);
assert(c.cancelCraft(c.craftingQueue[0].id));
assert.equal(c.availableCount('stone'),before);
choose('block');c.setCraftQuantity(max+1);
assert.equal(c.craft(),false);
assert.equal(c.availableCount('stone'),before);
c.openInventory();
w.ctx.document.querySelector('#craftMax').onclick();
assert.equal(c.craftQuantity,max);
w.ctx.document.querySelector('#craftLess').onclick();
assert.equal(c.craftQuantity,max-1);
w.ctx.document.querySelector('#craftMore').onclick();
assert.equal(c.craftQuantity,max);
assert(c.craft());
assert.equal(c.craftingQueue[0].qty,max*4);
assert(c.cancelCraft(c.craftingQueue[0].id));
assert.equal(c.availableCount('stone'),before);
// A real station recipe, matching the requested ingot example.
Object.assign(w.ctx.ship,{x:720,y:-870});
c.land(); c.surface[13][40]='furnace';c.addItem('metal',30);
c.save();
const station=boot(w.store).model.Colony;
assert(station.selectRecipe(station.recipes.findIndex(r=>r.out==='ingot')));
const recipe=station.recipes.find(r=>r.out==='ingot');
station.setCraftQuantity(10);
const ore=station.availableCount('metal'),ingots=station.availableCount('ingot');
assert(station.craft());
assert.equal(station.craftingQueue[0].qty,recipe.qty*10);
for(let i=0;i<station.craftSeconds(recipe)*10;i++)station.updateCrafting(1);
assert.equal(station.availableCount('ingot'),ingots+recipe.qty*10);
assert(station.availableCount('metal')<ore);
assert.equal(c.setCraftQuantity(NaN),false);
c.setCraftQuantity(-5);assert.equal(c.craftQuantity,1);
console.log('PASS: batch inputs/output/time, Max and +/- handlers, rejection, cancellation, reload and ten-ingot station crafting. No browser started.');
