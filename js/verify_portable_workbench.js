// Portable station access and real queue lifecycle. No browser or GPU.
const assert=require('node:assert/strict');
const {boot}=require('./verify_ships.js');
const setup=boot();
Object.assign(setup.ctx.ship,{x:720,y:-870});
setup.model.Colony.land();setup.model.Colony.surface[13][40]='bench';setup.model.Colony.save();
const w=boot(setup.store),c=w.model.Colony;
const recipe=c.recipes.find(r=>r.out==='portable_workbench');
assert(recipe&&recipe.station==='bench');
assert.equal(c.items.portable_workbench.maxStack,1);
assert.equal(c.craftSeconds(recipe),22.5);
const costs={};for(const type of recipe.pattern)if(type)costs[type]=(costs[type]||0)+1;
for(const [type,qty]of Object.entries(costs))assert(c.addItem(type,qty));
assert(c.selectRecipe(c.recipes.indexOf(recipe)));
assert(c.craft());for(let t=0;t<45;t++)c.updateCrafting(.5);
assert.equal(c.availableCount('portable_workbench'),1);
c.launch();Object.assign(w.ctx.ship,{x:5000,y:0});
assert.equal(c.getStationAccess().mode,'space');
assert(c.getStationAccess().stations.has('bench'));
assert(!c.getStationAccess().stations.has('furnace'));
const bases=c.getBases().length;
assert(c.addItem('ingot',8));
const plate=c.recipes.findIndex(r=>r.out==='plate');
assert(c.selectRecipe(plate));c.setCraftQuantity(2);
const before=c.availableCount('plate');
assert(c.craft());c.updateCrafting(.5);c.save();
const restored=boot(w.store),r=restored.model.Colony;
assert.equal(r.craftingQueue[0].remaining,3.5);
assert.equal(r.craftingQueue[0].batches,2);
assert(r.getStationAccess().stations.has('bench'));
assert(r.consumeItem('portable_workbench',1));
assert(!r.getStationAccess().stations.has('bench'));
r.updateCrafting(.5);assert.equal(r.craftingQueue[0].remaining,3.5);
assert(r.addItem('portable_workbench',1));
for(let t=0;t<7;t++)r.updateCrafting(.5);
assert.equal(r.availableCount('plate'),before+4);
assert.equal(r.availableCount('portable_workbench'),1);
assert.equal(r.craftingQueue.length,0);
assert.equal(r.getBases().length,bases);
r.openInventory();
assert(restored.ctx.document.querySelector('#slots .station-tabs').innerHTML!==null);
assert(r.selectRecipe(plate));assert(r.craft());
const ingots=r.availableCount('ingot');
assert(r.cancelCraft(r.craftingQueue[0].id));
assert.equal(r.availableCount('ingot'),ingots+2);
assert.equal(r.availableCount('portable_workbench'),1);
console.log('PASS: advanced recipe, 22.5-second fabrication, portable 3x3 access in space, no furnace/base, timed batches, save reload, removal pause, resume and cancellation. No browser started.');
