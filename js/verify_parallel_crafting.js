// Parallel furnace/workbench state machine, no browser or graphics context.
const assert=require('node:assert/strict');
const {boot}=require('./verify_ships.js');
const setup=boot();
Object.assign(setup.ctx.ship,{x:720,y:-870});
setup.model.Colony.land();
setup.model.Colony.surface[13][40]='bench';
setup.model.Colony.surface[13][41]='furnace';
setup.model.Colony.save();
const w=boot(setup.store),c=w.model.Colony;
const pick=(model,out)=>assert(model.selectRecipe(model.recipes.findIndex(r=>r.out===out)));
c.addItem('ingot',30);c.addItem('metal',30);
pick(c,'plate');c.setCraftQuantity(2);assert(c.craft());assert(c.craft());
pick(c,'ingot');assert(c.craft());assert(c.craft());
c.updateCrafting(1);
let jobs=c.craftingQueue;
assert.deepEqual(Array.from(jobs,j=>j.remaining),[7,8,3,4]);
c.save();
const restored=boot(w.store),r=restored.model.Colony;
assert.deepEqual(Array.from(r.craftingQueue,j=>j.remaining),[7,8,3,4]);
const plates=r.availableCount('plate'),ingots=r.availableCount('ingot');
for(let i=0;i<3;i++)r.updateCrafting(1);
assert.equal(r.availableCount('ingot'),ingots+1);
assert.equal(r.availableCount('plate'),plates);
assert.deepEqual(Array.from(r.craftingQueue,j=>j.remaining),[4,8,4]);
r.addItem('portable_workbench',1);
r.launch();Object.assign(restored.ctx.ship,{x:5000,y:0});
r.updateCrafting(1);
assert.deepEqual(Array.from(r.craftingQueue,j=>j.remaining),[3,8,4]);
for(let i=0;i<3;i++)r.updateCrafting(1);
assert.equal(r.availableCount('plate'),plates+4);
assert.deepEqual(Array.from(r.craftingQueue,j=>j.remaining),[8,4]);
const furnace=r.craftingQueue.find(j=>j.station==='furnace');
const ore=r.availableCount('metal');
assert(r.cancelCraft(furnace.id));
assert.equal(r.availableCount('metal'),ore+1);
assert.equal(r.craftingQueue.length,1);
// Twelve slots per lane, saved together without losing jobs beyond index 12.
const full=boot(setup.store),f=full.model.Colony;
f.addItem('ingot',30);f.addItem('metal',30);
pick(f,'plate');for(let i=0;i<12;i++)assert(f.craft());
assert.equal(f.craft(),false);
pick(f,'ingot');for(let i=0;i<12;i++)assert(f.craft());
assert.equal(f.craft(),false);
f.save();
const loaded=boot(full.store).model.Colony;
assert.equal(loaded.craftingQueue.length,24);
assert.equal(loaded.craftingQueue.filter(j=>j.lane==='furnace').length,12);
loaded.updateCrafting(1);
assert.equal(loaded.craftingQueue[0].remaining,3);
assert.equal(loaded.craftingQueue[12].remaining,3);
loaded.openInventory();
console.log('PASS: simultaneous timers, independent FIFO completion/pause, cancellation refunds, portable bench, two 12-job limits and 24-job save/reload. No browser started.');
