// Crafting queue state machine and persistence checks. No browser or WebGL.
const assert = require('node:assert/strict');
const fs = require('node:fs'), path = require('node:path');
const {boot} = require('./verify_ships.js');
const {functionSource} = require('./test_source_utils.js');
const byOutput = (c, type) => c.recipes.findIndex(recipe => recipe.out === type);
const w = boot(), c = w.model.Colony;
assert(c.selectRecipe(byOutput(c, 'block')));
const blocks = c.availableCount('block'), stones = c.availableCount('stone'), mass = c.cargoMass;
assert(c.craft());
assert.equal(c.availableCount('block'), blocks);
assert.equal(c.availableCount('stone'), stones - 2);
assert.equal(c.cargoMass, mass);
assert.equal(c.craftingQueue[0].duration, 2);
c.updateCrafting(1);
assert.equal(c.availableCount('block'), blocks);
assert.equal(c.craftingQueue[0].remaining, 1);
c.save();
const resumed = boot(w.store).model.Colony;
assert.equal(resumed.craftingQueue[0].remaining, 1);
resumed.updateCrafting(1);
assert.equal(resumed.availableCount('block'), blocks + 4);
assert.equal(resumed.craftingQueue.length, 0);
resumed.updateCrafting(1);
assert.equal(resumed.availableCount('block'), blocks + 4);
// Fabrication progresses in the paused inventory frame without advancing physics.
w.ctx.GameAudio.setEngine = () => {};
w.ctx.paused = true; w.ctx.last = 0;
w.ctx.render = () => {};
w.ctx.update = () => {throw Error('Paused physics must not run');};
w.ctx.requestAnimationFrame = () => {};
w.run(functionSource(fs.readFileSync(path.join(__dirname, 'game.js'), 'utf8'), 'frame'));
w.run('frame(1000)');
assert(c.craftingQueue[0].remaining < 1);
assert(c.craftingQueue[0].remaining > .9);
assert(c.cancelCraft(c.craftingQueue[0].id));
assert.equal(c.availableCount('stone'), stones);
assert.equal(c.cancelCraft(999), false);
// FIFO capacity and machine durations; failed enqueue spends nothing.
assert(c.addItem('stone', 64));
assert(c.selectRecipe(byOutput(c, 'block')));
for (let i = 0; i < 12; i++) assert(c.craft());
const reserved = c.availableCount('stone');
assert.equal(c.craft(), false);
assert.equal(c.availableCount('stone'), reserved);
const copy = c.craftingQueue; copy[0].remaining = 0;
assert.equal(c.craftingQueue[0].remaining, 2);
const second = c.craftingQueue[1].id;
c.updateCrafting(1);
assert.equal(c.craftingQueue[1].remaining, 2);
assert(c.cancelCraft(second));
assert.equal(c.availableCount('stone'), reserved + 2);
assert(c.craftSeconds(c.recipes[byOutput(c, 'bench')]) > c.craftSeconds(c.recipes[byOutput(c, 'block')]));
// Station-bound jobs pause when the source workshop is disconnected.
const initial = boot();
initial.ctx.ship.x = 720; initial.ctx.ship.y = -870;
initial.model.Colony.land();
initial.model.Colony.surface[13][40] = 'bench';
initial.model.Colony.surface[13][41] = 'furnace';
initial.model.Colony.save();
const base = boot(initial.store), b = base.model.Colony;
assert(b.addItem('ingot', 2));
assert(b.selectRecipe(byOutput(b, 'plate')));
assert(b.craft());
b.updateCrafting(1);
assert.equal(b.craftingQueue[0].remaining, 3);
b.launch();
const moon = b.getStationAccess().moon;
base.ctx.ship.x = moon.x + moon.r + 221; base.ctx.ship.y = moon.y;
b.updateCrafting(1);
assert.equal(b.craftingQueue[0].remaining, 3);
base.ctx.ship.x = moon.x; base.ctx.ship.y = moon.y - moon.r - 40;
b.updateCrafting(1);
assert.equal(b.craftingQueue[0].remaining, 2);
b.save();
const data = JSON.parse(base.store.get('spacecraft-save-v1'));
data.terrains.find(([id]) => id === '0:0')[1][13][40] = null;
const removed = boot([['spacecraft-save-v1', JSON.stringify(data)]]).model.Colony;
removed.updateCrafting(1);
assert.equal(removed.craftingQueue[0].remaining, 2);
// A full hold retains completed output, including over a reload.
const full = boot(initial.store), f = full.model.Colony;
assert(f.selectRecipe(byOutput(f, 'ingot')));
assert(f.craft());
assert(f.addItem('stone', (f.bag.length - f.bag.filter(Boolean).length) * 64));
for (let i = 0; i < 4; i++) f.updateCrafting(1);
assert.equal(f.availableCount('ingot'), 0);
assert.equal(f.craftingQueue[0].remaining, 0);
assert.equal(f.cancelCraft(f.craftingQueue[0].id), false);
const ready = boot(full.store).model.Colony;
assert.equal(ready.craftingQueue[0].remaining, 0);
assert(ready.consumeItem('stone', 64));
ready.updateCrafting(.1);
assert.equal(ready.availableCount('ingot'), 1);
assert.equal(ready.craftingQueue.length, 0);
// Cancel refunds cannot lose materials when even the original slot was filled.
const refund = boot(initial.store), r = refund.model.Colony;
assert(r.addItem('ingot', 2));
assert(r.selectRecipe(byOutput(r, 'plate'))); assert(r.craft());
assert(r.addItem('stone', (r.bag.length - r.bag.filter(Boolean).length) * 64));
assert(r.cancelCraft(r.craftingQueue[0].id));
assert.equal(r.count('ingot'), 2);
assert.equal(r.availableCount('ingot'), 0);
const returned = boot(refund.store).model.Colony;
assert.equal(returned.count('ingot'), 2);
assert.equal(returned.craftingQueue.length, 0);
console.log('PASS: delayed FIFO output, ingredient reservation/mass, queue capacity, cancellation/refund overflow, menu ticking, timed save/reload, machine durations, station/range pause and full-hold completion safety. No browser started.');
