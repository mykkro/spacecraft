// Moon-owned crafting queues: capacity, scheduling, UI and persistence without a browser.
const assert=require('node:assert/strict');
const {boot}=require('./verify_ships.js');
const setup=boot();
Object.assign(setup.ctx.ship,{x:720,y:-870});
setup.model.Colony.land();setup.model.Colony.surface[13][40]='bench';setup.model.Colony.surface[13][41]='furnace';setup.model.Colony.save();
let w=boot(setup.store),c=w.model.Colony;
const a=c.getStationAccess().moon;
const pick=(out)=>assert(c.selectRecipe(c.recipes.findIndex(r=>r.out===out)));
const fill=()=>{
  c.addItem('ingot',30);c.addItem('metal',30);
  pick('plate');for(let i=0;i<12;i++)assert(c.craft());
  assert.equal(c.craft(),false);
  pick('ingot');for(let i=0;i<12;i++)assert(c.craft());
  assert.equal(c.craft(),false);
};
fill();assert.equal(c.craftingQueue.length,24);
const idsA=new Set(Array.from(c.craftingQueue,j=>j.id));
const b=c.getMoons().find(m=>m.id!==a.id&&Math.hypot(m.x-a.x,m.y-a.y)>2000);
assert(b);
c.launch();Object.assign(w.ctx.ship,{x:b.x,y:b.y-b.r-90});c.land();
assert.equal(c.getStationAccess().moon.id,b.id);
c.surface[13][40]='bench';c.surface[13][41]='furnace';c.save();
w=boot(w.store);c=w.model.Colony;
fill();assert.equal(c.craftingQueue.length,48,'Another moon has independent limits');
c.updateCrafting(.5);
assert(c.craftingQueue.filter(j=>idsA.has(j.id)).every(j=>j.remaining===2));
const jobsB=c.craftingQueue.filter(j=>j.owner===b.id);
assert.equal(jobsB[0].remaining,1.5);assert.equal(jobsB[12].remaining,1.5);
c.openInventory();
const markup=w.ctx.document.querySelector('#craftQueue').innerHTML;
for(const id of idsA)assert(!markup.includes('id="craftJobStatus'+id+'"'));
assert(markup.includes(b.name));
const aJob=c.craftingQueue.find(j=>j.owner===a.id);
assert.equal(c.cancelCraft(aJob.id),false);
c.save();w=boot(w.store);c=w.model.Colony;
assert.equal(c.craftingQueue.length,48,'All moons survive reload, beyond former 24-job cap');
assert(c.craftingQueue.filter(j=>j.owner===a.id).every(j=>j.remaining===2));
c.launch();Object.assign(w.ctx.ship,{x:a.x,y:a.y-a.r-90});c.land();
c.updateCrafting(.5);
assert.equal(c.craftingQueue.find(j=>j.owner===a.id).remaining,1.5);
assert.equal(c.craftingQueue.find(j=>j.owner===b.id).remaining,1.5);
assert(c.cancelCraft(aJob.id));
const left=c.craftingQueue.filter(j=>j.owner===a.id).length;
assert.equal(left,23);
console.log('PASS: independent moon/station capacity, local visibility/timers, remote cancellation guards, return/resume and 48-job save reload. No browser started.');
